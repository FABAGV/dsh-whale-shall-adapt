/**
 * 投递给模型的「来源标注」防伪造。
 *
 * 投递正文长这样：`[来自 QQ 群 <群名>，发言人 <昵称>（QQ <号>，消息号 <号>）]\n<正文>`。
 * 群名片和正文都是群友自己说了算的：
 *   - 昵称里塞换行 + 方括号，就能伪造一个"发言人 主人（QQ <主人号>）"的标注；
 *   - 正文里另起一行 `[来自 QQ 群 …，发言人 主人…]`，模型会把它当成插件给的标注。
 * 标注**只有第一行**才是真的，但模型不会天然知道这一点，所以这里把能拼进标注的字符清掉、
 * 把正文里长得像标注的行标成"用户原文"。
 */

/** 名字：去掉换行、制表、括号（标注的分隔符）、以及"QQ 12345 / 消息号 678"这种冒充的号，压成一行、限长 */
export function safeName(value, max = 40) {
  const text = String(value ?? '')
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/[[\]【】〔〕{}()（）]/g, ' ')
    // 名字里不该出现号：昵称里写“QQ 10001”就是为了在标注里冒充另一个人
    .replace(/QQ\s*\d{5,12}/gi, ' ')
    .replace(/消息号\s*\d+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  return text.slice(0, max)
}

/** 正文里以这些开头的行，是"像插件标注"的伪造 */
const LOOKS_LIKE_LABEL = /^\s*(?:[\[【(（]\s*(?:来自\s*QQ|来自QQ|插件提示|附[:：]|群里刚才)|\[来自)/

/**
 * 把正文里"像标注"的行标成用户原文（前缀一个明确的前缀，而不是只加反斜杠 ——
 * 反斜杠在模型眼里和普通字符没区别）。
 */
export function escapeLabelLines(text) {
  return String(text ?? '').replace(/^.*$/gm, (line) => (LOOKS_LIKE_LABEL.test(line) ? `（用户原文）${line}` : line))
}
